const out = {};
for (const n of names) {
  const f = path.join(dir, n + '.svg');
  if (!fs.existsSync(f)) {
    console.warn('missing', n);
    continue;
  }
  out[n] = fs
    .readFileSync(f, 'utf8')
    .replace(/<svg[^>]*>/, '')
    .replace('</svg>', '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}
